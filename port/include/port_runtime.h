/* Native port runtime interface (see docs/PORT.md).  Only port/ code includes this. */
#ifndef PORT_RUNTIME_H
#define PORT_RUNTIME_H

typedef unsigned int u32p;
/* ret: how the result reaches a MIPS caller (0 = 32 bits, 1 = u8, 2 = s8, 3 = u16, 4 = s16, 5 = void: gen_t2.py) */
typedef struct { u32p addr; void *fn; const char *name; int ret; int ovl; u32p w0, w1; } PortFunc;
/* ovl: 0 = MAIN, else an index into port_ovls; w0 / w1: the function's first two code words in its overlay file
   (the native copy is used only while those bytes are in RAM and its overlay is the last one loaded there) */
typedef struct { const char *name, *file; u32p vram; } PortOvl;
extern const PortOvl port_ovls[];
extern const int port_ovls_count;
void port_ovl_loaded(const char *file);   /* the virtual disc saw sector 0 of BIN/<X>.BIN read */
const PortFunc *port_lookup_func(u32p addr);
typedef struct { u32p addr; int pure; const char *name; const char *lib; } PortLibAddr;

/* generated by port/tools/gen_t2.py link (funcmap.c) */
extern const PortFunc port_funcmap[];
extern const int port_funcmap_count;
/* shims by the retail address of the Psy-Q function they replace */
typedef struct { u32p addr; void *fn; const char *name; } PortLib;
extern const PortLib port_libmap[];
extern const int port_libmap_count;
extern const PortLibAddr port_libaddrs[];
extern const int port_libaddrs_count;
int port_is_lib_addr(u32p addr);
/* MIPS interpreter (runtime/mips_interp.c) for code without C */
extern u32p port_mips_pending;
extern int port_interp;          /* 0: --no-interp (stub instead) */
u32p port_mips_entry(u32p, u32p, u32p, u32p, u32p, u32p, u32p, u32p);
int port_mips_calls(void);
/* fault diagnostics (runtime/sys_common.c): nearest native function below a host address (0: none within 16 KB),
   the stack words in [lo, hi) with their symbols, the last call thunk port_resolve_call answered */
const char *port_sym_near(unsigned long a, unsigned long *off);
void port_dump_stack(const unsigned long *sp, unsigned long lo, unsigned long hi);
extern u32p port_last_resolve_addr; extern const char *port_last_resolve_name; extern void *port_last_resolve_fn;
void port_note_resolve(u32p addr, const char *name, void *fn);
/* accesses below 0x200000 the host cannot map (sys_common.c): PORT_LOW_JUMP = continue at *neweip (a rewritten copy
   of the instruction in the executable `scratch` page), PORT_LOW_REGS = a string instruction: the caller moves
   ESI/EDI below 0x200000 to KSEG0 and restarts it; 0 = not handled */
#define PORT_LOW_JUMP 1
#define PORT_LOW_REGS 2
int port_low_emulate(unsigned long eip, unsigned long fault, unsigned char *scratch, unsigned long *neweip);
void port_low_report(void);
/* Psy-Q functions of MAIN by retail address (gen_t2.py): pure = plain CPU / GTE code the interpreter may run when
   no shim exists; the others touch hardware and are logged stubs */
const PortLibAddr *port_lib_info(u32p addr);
#define PORT_OVL_BASE 0x80106228u      /* lowest overlay load address (GAME / DEMO); areas 0x80108F9C, OPN 0x8018A000 */
#define PORT_OVL_END  0x80200000u
/* PS1 address space emulated in the process: RAM (2 MB, mirrored nowhere) and the scratchpad + I/O page */
#define PSX_RAM_BASE   0x80000000u
#define PSX_RAM_SIZE   0x00200000u
#define PSX_SPAD_BASE  0x1F800000u
#define PSX_SPAD_SIZE  0x00004000u   /* scratchpad 1 KB + hardware registers 0x1F801000.. as plain memory */

/* libc subset (freestanding build: no host libc in the i386 prototype) */
void port_puts(const char *s);
void port_printf(const char *fmt, ...);
int port_vsnprintf(char *buf, int n, const char *fmt, __builtin_va_list ap);
void port_exit(int code) __attribute__((noreturn));
void port_quit(int code) __attribute__((noreturn));   /* normal exit: pacing summary + low-access tally, then port_exit (shims/psyq.c) */
void port_fatal(const char *fmt, ...) __attribute__((noreturn));

/* host file access */
int port_open(const char *path);
int port_read(int fd, void *buf, int n);
int port_pread(int fd, void *buf, int n, long long off);
void port_close(int fd);
int port_create(const char *path);              /* write-only, truncates */
int port_open_pipe(const char *path);           /* read-write (a FIFO opens without waiting for the reader) */
int port_write(int fd, const void *buf, int n);
int port_pwrite(int fd, const void *buf, int n, long long off);
int port_mkdir(const char *path);
long long port_filesize(int fd);

/* time */
unsigned long long port_time_us(void);
void port_sleep_us(unsigned long long us);
void port_sleep_until_us(unsigned long long deadline);   /* absolute port_time_us() deadline */

/* call resolution: native function for a retail code address (current overlay first) */
void *port_lookup(u32p addr);
int port_lookup_ret(u32p addr);   /* the PortFunc ret kind of the native game function at addr (0 when none) */
void *port_resolve_call(u32p addr, const char *name);
void port_stub(const char *name, u32p addr);
/* sys_lookup.c, for the hosts' fault handlers */
int port_interpretable(u32p addr);
int port_stub_ret0(void);
const char *port_lib_name(u32p addr, const char *name);

/* cooperative threads (Psy-Q OpenTh/ChangeTh) */
int port_thread_open(void *fn);
void port_thread_change(int handle);
void port_thread_close(int handle);

/* frame pacing / vblank */
void port_vblank(void);          /* one emulated vertical blank: runs the game's VSync event handlers */
extern int port_frame;
extern int port_max_frames;      /* stop after this many vblanks (0 = no limit) */
extern int port_verbose;
extern int port_kuseg_strict;    /* --kuseg-strict: Windows, stop when the KUSEG mirror is partly mapped */

/* CD image */
int port_cd_open(const char *path);
int port_cd_read_sectors(int lba, int count, void *dst, int sector_bytes);
extern int port_trace_cd;        /* --trace-cd: log every Setloc and sector read */
int port_last_error(void);       /* errno / GetLastError of the last port_pread */

/* GPU (shims/gpu.c): software rasteriser into emulated VRAM, frame dumps */
extern const char *port_dump_dir;    /* --dump-frames DIR: write the displayed frame as PNG */
extern int port_dump_every;          /* --dump-every N (default 10) */
extern int port_dump_vram;           /* --dump-vram: also write the whole 1024x512 VRAM */
void port_gpu_vblank(void);
#endif
